      <section className="mt-10" id="app-limits">
        <h2 className="font-serif text-2xl text-fg">
          Appendix A. Limitations and dual-use
        </h2>
        <p className="mt-4">
          <span className="font-medium">What the results establish.</span> In a
          controlled setting with four short sources, eight inexpensive
          production models moved toward a false claim under each free signal,
          ignored a failed signature check in their first answer, and let page
          text override the system’s report. The differences between conditions
          are the finding; absolute rates depend on the setting.
        </p>
        <p className="mt-4 font-medium">What they do not establish.</p>
        <ul className="mt-3 list-disc space-y-2 pl-5">
          <li>
            <em>Realism.</em> Sources are short, templated and attributed to
            fictional publishers. Real engines retrieve more and noisier pages
            and may filter before generation.
          </li>
          <li>
            <em>Model class.</em> We tested small and mid-sized models chosen
            to fit a $4 budget. They are typical of models used for
            summarization at scale, but frontier and reasoning models may
            behave differently.
          </li>
          <li>
            <em>Bundled cues.</em> The GEO page combines an invented statistic,
            an expert quote, an authoritative title and a restated claim, so
            its effect cannot be attributed to one tactic. The independent
            sources carry their own cheap authority cues (see Section 5).
          </li>
          <li>
            <em>Credentials as text.</em> Pipelines that never show credential
            text to the model avoid the badge attack, but they still face
            styling, repetition and self-declared verification.
          </li>
          <li>
            <em>Sampling.</em> One sample per prompt at temperature 0.7
            (gpt-5-nano at the provider default). Per-model cells (n = 60 or
            120) have no intervals and should be read as descriptive.
          </li>
          <li>
            <em>Scoring.</em> No human labels were collected. Scoring is
            deterministic string matching on a required answer line present in
            at least 98.8% of replies; a manual check of 20 hedged or unparsed
            lines found no errors, but a full inter-rater check remains to be
            done.
          </li>
          <li>
            <em>Follow-up and confidence.</em> We used one fixed, neutral
            follow-up; adversarial or supportive follow-ups would change
            recovery. Stated confidence is a verbal report, not a computed
            probability. All prompts are in English.
          </li>
        </ul>
        <p className="mt-4">
          <span className="font-medium">Dual use.</span> The manipulations we
          study (copied credential text, self-declared verification, syndication
          and invented statistics) are already in use and documented in the
          related work. We used fictional publishers and harmless facts such as
          dates, capitals and measurements; no real organisation’s branding was
          imitated, and we neither built nor ran an attack optimized for any
          real query or live engine. The spoof result does show that a one-line
          imitation of a verification message is effective. We think reporting
          it does more good than harm, because the mitigation (enforcing
          verification in the pipeline and stripping verification-like text from
          pages) is simple and is described here. Model outputs were never
          shown to real users.
        </p>
        <p className="mt-4">
          <span className="font-medium">Personal data.</span> None. Void items
          describe invented entities, and known items are public facts.
        </p>
        <p className="mt-4">
          <span className="font-medium">Prior work.</span> The framing builds on
          the author’s earlier essay <Cite n={7} />. No code or data predates
          the sprint; all code, items, prompts, model runs and analyses were
          produced during it (13–15 November 2026).
        </p>
      </section>

